"""deskman — Hyprland monitor manager (Omarchy-style Lua configs).

Edits ~/.config/hypr/monitors.lua from a GUI: drag the monitor layout,
pick resolutions/refresh rates from EDID, set scale, then apply + verify.

Single file, GTK4/Libadwaita, no deps beyond what Omarchy ships.
"""
