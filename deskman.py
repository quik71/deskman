CONFIG_DIR = Path(os.path.expanduser("~/.config/hypr"))
MONITORS_LUA = CONFIG_DIR / "monitors.lua"
BACKUP_LUA = CONFIG_DIR / "monitors.lua.bak-deskman"
PRE_DESKMAN = CONFIG_DIR / "monitors.lua.pre-deskman"
STATE_DIR = Path(os.path.expanduser("~/.config/deskman"))
STATE_FILE = STATE_DIR / "state.json"

MODE_RE = re.compile(r"^(\d+)x(\d+)@([\d.]+)Hz$")
SCALE_CHOICES = [1.0, 1.25, 1.5, 1.75, 2.0, 2.5, 3.0]
SNAP_PX = 30  # layout-px snap threshold

GENERATED_HEADER = """\
-- ============================================================
-- GENERATED by deskman — edit with `deskman`, not by hand.
-- Rules below are in left-to-right desk order.
-- Positions are "XxY" in logical px (plain decimal; the x is a separator).
-- App state: {state_file}
-- ============================================================
"""


def sh(*args, env_extra=None, timeout=15):
    env = dict(os.environ)
    if env_extra:
        env.update(env_extra)
    try:
        r = subprocess.run(args, capture_output=True, text=True, timeout=timeout, env=env)
        return r.returncode, r.stdout, r.stderr
    except Exception as e:  # noqa: BLE001
        return 1, "", str(e)


def hypr_env():
    """Env needed to reach the running Hyprland (also works from a plain shell)."""
    rt = os.environ.get("XDG_RUNTIME_DIR") or f"/run/user/{os.getuid()}"
    env = {"XDG_RUNTIME_DIR": rt}
    hs = os.environ.get("HYPRLAND_INSTANCE_SIGNATURE")
    hdir = Path(rt) / "hypr"
    if not hs and hdir.is_dir():
        entries = sorted(p.name for p in hdir.iterdir())
        if entries:
            hs = entries[0]
    if hs:
        env["HYPRLAND_INSTANCE_SIGNATURE"] = hs
    if not os.environ.get("WAYLAND_DISPLAY"):
        wl = sorted(Path(rt).glob("wayland-*"))
        if wl:
            env["WAYLAND_DISPLAY"] = wl[-1].name
    return env


def hyprctl_json(*args):
    rc, out, err = sh("hyprctl", *args, env_extra=hypr_env())
    if rc != 0:
        raise RuntimeError(f"hyprctl {' '.join(args)} failed: {(err or out).strip()}")
    return json.loads(out)


def fmt_num(v):
    f = float(round(float(v), 4))
    return str(int(f)) if f == int(f) else repr(f)


def backup_lua_once():
    """On first takeover, freeze the hand-tuned original into .pre-deskman."""
    if MONITORS_LUA.is_file() and "GENERATED by deskman" not in MONITORS_LUA.read_text():
        if not PRE_DESKMAN.exists():
            PRE_DESKMAN.write_text(MONITORS_LUA.read_text())
        BACKUP_LUA.write_text(MONITORS_LUA.read_text())


def logical_size(w, h, scale):
    return math.floor(w / scale), math.floor(h / scale)


class Monitor:
    """One output's desired layout state (mutable, then serialized)."""

    def __init__(self, name, model="", make="", modes=None, w=0, h=0, rate="", rate_f=0.0,
                 x=0, y=0, scale=1.0, connected=False, phys_mm=(0, 0)):
        self.name = name
        self.model = model
        self.make = make
        self.modes = modes or []          # list of (w, h, rate_display, rate_float)
        self.w, self.h, self.rate, self.rate_f = w, h, rate, rate_f
        self.x, self.y, self.scale = int(x), int(y), float(scale)
        self.connected = connected
        self.phys_mm = tuple(phys_mm)

    @property
    def logical(self):
        return logical_size(self.w, self.h, self.scale)

    def resolutions(self):
        seen, out = set(), []
        for w, h, _r, _rf in self.modes:
            if (w, h) not in seen:
                seen.add((w, h))
                out.append((w, h))
        return out

    def rates_for(self, w, h):
        return [(r, rf) for mw, mh, r, rf in self.modes if (mw, mh) == (w, h)]

    def mode_match(self, w, h, rf):
        """Find the exact EDID token for the current mode; tolerate tiny float drift."""
        for mw, mh, r, mrf in self.modes:
            if mw == w and mh == h and abs(mrf - rf) < 0.05:
                return r, mrf
        for mw, mh, r, mrf in self.modes:
            if mw == w and mh == h:
                return r, mrf
        return None, None

    def pick_resize(self, target_logical_w):
        """Nearest EDID resolution to a dragged logical width (current scale).
        Only reported resolutions — never invented sizes."""
        cands = []
        for w, h in self.resolutions():
            lw = math.floor(w / self.scale)
            cands.append((abs(lw - target_logical_w), w, h))
        if not cands:
            return None
        cands.sort()
        _d, w, h = cands[0]
        same = [r for r in self.rates_for(w, h) if abs(r[1] - self.rate_f) < 0.05]
        if same:
            disp, rf = same[0]
        else:  # keep it boring: highest refresh for that res
            disp, rf = max(self.rates_for(w, h), key=lambda r: r[1])
        return w, h, disp, rf

    def to_dict(self):
        return {"name": self.name, "model": self.model, "make": self.make, "modes": self.modes,
                "w": self.w, "h": self.h, "rate": self.rate, "rate_f": self.rate_f,
                "x": self.x, "y": self.y, "scale": self.scale, "phys_mm": list(self.phys_mm)}

    @staticmethod
    def from_dict(d):
        return Monitor(d["name"], d.get("model", ""), d.get("make", ""),
                       [tuple(m) for m in d.get("modes", [])], d.get("w", 0), d.get("h", 0),
                       d.get("rate", ""), float(d.get("rate_f", 0)), d.get("x", 0), d.get("y", 0),
                       float(d.get("scale", 1.0)), False, tuple(d.get("phys_mm", (0, 0))))


class Model:
    """Desired layout; live hyprctl state is truth for connected outputs.

    Offline outputs keep their saved rule so hotplug brings them back where
    they belong instead of auto-placed like a lost puppy.
    """

    def __init__(self):
        self.monitors = {}       # name -> Monitor (desired state)
        self.gdk_scale = 2
        self.note = ""

    def load_state(self):
        if STATE_FILE.is_file():
            try:
                d = json.loads(STATE_FILE.read_text())
                for md in d.get("monitors", []):
                    m = Monitor.from_dict(md)
                    self.monitors[m.name] = m
                self.gdk_scale = int(d.get("gdk_scale", 2))
            except Exception as e:  # noqa: BLE001
                self.note = f"ignored unreadable state file: {e}"

    def save_state(self):
        STATE_DIR.mkdir(parents=True, exist_ok=True)
        STATE_FILE.write_text(json.dumps(
            {"monitors": [m.to_dict() for m in self.ordered()], "gdk_scale": self.gdk_scale},
            indent=2))

    def refresh_live(self):
        """Pull live hyprctl state. Connected outputs adopt live mode/pos/scale;
        positions/modes for offline outputs keep whatever is saved."""
        data = hyprctl_json("monitors", "all", "-j")
        live_names = set()
        for raw in data:
            name = raw["name"]
            if raw.get("disabled") or int(raw.get("width", 0)) == 0:
                continue  # disabled output: junk geometry, keep saved layout
            live_names.add(name)
            modes = []
            for tok in raw.get("availableModes", []):
                mt = MODE_RE.match(tok)
                if mt:
                    modes.append((int(mt.group(1)), int(mt.group(2)),
                                  mt.group(3), float(mt.group(3))))
            w, h = int(raw["width"]), int(raw["height"])
            rf = float(raw.get("refreshRate", 0))
            m = Monitor(name, raw.get("model", "") or raw.get("description", ""),
                        raw.get("make", ""), modes, w, h, "", rf,
                        int(float(raw["x"])), int(float(raw["y"])),
                        float(raw.get("scale", 1.0)), True,
                        (int(raw.get("physicalWidth", 0)), int(raw.get("physicalHeight", 0))))
            disp, rf2 = m.mode_match(w, h, rf)
            if disp:
                m.rate, m.rate_f = disp, rf2
            old = self.monitors.get(name)
            if old:
                m.model = m.model or old.model
                m.make = m.make or old.make
                m.modes = m.modes or old.modes
                m.rate, m.rate_f = (disp, rf2) if disp else (old.rate, m.rate_f or old.rate_f)
            self.monitors[name] = m
        for name, m in self.monitors.items():
            m.connected = name in live_names
        if not self.monitors:
            self.note = "hyprctl returned no outputs — is Hyprland running?"

    def ordered(self):
        return sorted(self.monitors.values(), key=lambda m: (m.x, m.y, m.name))

    def overlaps(self):
        ms = [m for m in self.monitors.values() if m.w > 0]
        bad = []
        for i in range(len(ms)):
            for j in range(i + 1, len(ms)):
                a, b = ms[i], ms[j]
                aw, ah = a.logical
                bw, bh = b.logical
                if (a.x < b.x + bw and b.x < a.x + aw and
                        a.y < b.y + bh and b.y < a.y + ah):
                    bad.append((a.name, b.name))
        return bad

    def pack_row(self):
        """Always-magnetic row: order by rectangle CENTERS (drag 1 onto 3 = it
        becomes #3), re-derive all x from logical widths. Y stays per-monitor
        (vertical calibration is real desk ergonomics; horizontal gaps never are)."""
        ms = [m for m in self.monitors.values() if m.w > 0]
        ms.sort(key=lambda m: (m.x + m.logical[0] // 2, m.y, m.name))
        x = 0
        for m in ms:
            m.x = x
            x += m.logical[0]
        return ms

    def bounds(self):
        ms = [m for m in self.monitors.values() if m.w > 0]
        if not ms:
            return 0, 0, 1, 1
        x0 = min(m.x for m in ms)
        y0 = min(m.y for m in ms)
        x1 = max(m.x + m.logical[0] for m in ms)
        y1 = max(m.y + m.logical[1] for m in ms)
        return x0, y0, max(1, x1 - x0), max(1, y1 - y0)

    def gen_lua(self):
        out = [GENERATED_HEADER.format(state_file=STATE_FILE)]
        out.append("-- GTK/XWayland apps only honor integer GDK_SCALE; keep it near the center scale.")
        out.append(f'hl.env("GDK_SCALE", "{int(self.gdk_scale)}")')
        out.append("")
        for m in self.ordered():
            mode = f"{m.w}x{m.h}@{m.rate}" if m.rate else "preferred"
            tag = " (offline — rule preserved)" if not m.connected else ""
            out.append(f"-- {m.make} {m.model}{tag}".rstrip())
            out.append(f'hl.monitor({{ output = "{m.name}", mode = "{mode}", '
                       f'position = "{int(m.x)}x{int(m.y)}", scale = {fmt_num(m.scale)} }})')
        out.append("")
        out.append("-- safety net: any unlisted/hotplugged output gets auto-placed")
        out.append('hl.monitor({ output = "", mode = "preferred", position = "auto", scale = 1 })')
        out.append("")
        return "\n".join(out)


class Deskman(Adw.Application):
    def __init__(self):
        super().__init__(application_id="land.hypr.deskman",
                         flags=Gio.ApplicationFlags.FLAGS_NONE)
        self.model = Model()
        self.selected = None
        self.win = None
        self._drag = None
        self._view = None

    def do_startup(self):
        Adw.Application.do_startup(self)
        self.model.load_state()
        try:
            self.model.refresh_live()
        except Exception as e:  # noqa: BLE001
            self.model.note = f"hyprctl failed: {e}"
        self.build_window()
        self.refresh_ui()

    def do_activate(self):
        if self.win:
            self.win.present()

    # ---------- UI construction ----------
    def build_window(self):
        win = Adw.ApplicationWindow(application=self)
        self.win = win
        win.set_title("deskman — Hyprland monitor manager")
        win.set_default_size(1280, 800)

        toolbar = Adw.ToolbarView()
        header = Adw.HeaderBar()
        for label, cb in [("Reload", self.on_reload),
                          ("Write only", self.on_write_only), ("Apply", self.on_apply)]:
            btn = Gtk.Button(label=label)
            btn.connect("clicked", cb)
            if label == "Apply":
                btn.add_css_class("suggested-action")
            header.pack_end(btn)
        toolbar.add_top_bar(header)

        toast = Adw.ToastOverlay()
        self.toast_overlay = toast
        hbox = Gtk.Box(orientation=Gtk.Orientation.HORIZONTAL)

        self.canvas = Gtk.DrawingArea()
        self.canvas.set_hexpand(True)
        self.canvas.set_vexpand(True)
        self.canvas.set_content_width(800)
        self.canvas.set_content_height(600)
        self.canvas.set_draw_func(self.on_draw)
        motion = Gtk.EventControllerMotion()
        motion.connect("motion", self.on_motion)
        gesture = Gtk.GestureClick()
        gesture.connect("pressed", self.on_press)
        gesture.connect("released", self.on_release)
        for c in (motion, gesture):
            self.canvas.add_controller(c)
        hbox.append(self.canvas)

        side = Gtk.ScrolledWindow()
        side.set_policy(Gtk.PolicyType.NEVER, Gtk.PolicyType.AUTOMATIC)
        side.set_size_request(390, -1)
        sidebox = Gtk.Box(orientation=Gtk.Orientation.VERTICAL, spacing=8)
        for m in ("start", "end", "top", "bottom"):
            getattr(sidebox, f"set_margin_{m}")(10)
        self.status_label = Gtk.Label(label="", wrap=True, xalign=0)
        self.status_label.add_css_class("dim-label")
        sidebox.append(self.status_label)

        self.output_group = Adw.PreferencesGroup(title="Outputs")
        self.listbox = Gtk.ListBox()
        self.listbox.set_selection_mode(Gtk.SelectionMode.SINGLE)
        self.listbox.connect("row-selected", self.on_select_row)
        self.list_rows = {}
        self.output_group.add(self.listbox)
        sidebox.append(self.output_group)

        self.detail_slot = Gtk.Box(orientation=Gtk.Orientation.VERTICAL)
        sidebox.append(self.detail_slot)
        sidebox.append(self.make_gdk_group())
        side.set_child(sidebox)
        self.sidebox = sidebox
        hbox.append(side)

        toast.set_child(hbox)
        toolbar.set_content(toast)
        win.set_content(toolbar)

        css = b".canvas { background-color: #1d1f24; }"
        provider = Gtk.CssProvider()
        provider.load_from_data(css)
        Gtk.StyleContext.add_provider_for_display(
            Gdk.Display.get_default(), provider,
            Gtk.STYLE_PROVIDER_PRIORITY_APPLICATION)

        self.build_output_rows()
        win.present()

    def make_gdk_group(self):
        g = Adw.PreferencesGroup(title="XWayland / GDK")
        row = Adw.SpinRow.new_with_range(1, 4, 1)
        row.set_title("GDK_SCALE")
        row.set_subtitle("integer scale for GTK/XWayland apps")
        row.set_value(float(self.model.gdk_scale))
        row.connect("changed", self.on_gdk_changed)
        g.add(row)
        return g

    def on_gdk_changed(self, row):
        self.model.gdk_scale = int(row.get_value())

    def build_output_rows(self):
        # clear old rows first — calling this twice must not stack duplicates
        while (r := self.listbox.get_first_child()) is not None:
            self.listbox.remove(r)
        self.list_rows = {}
        for m in self.model.ordered():
            row = Adw.ActionRow(title=f"{m.name} — {m.model}".strip(" —"))
            row.mon_name = m.name
            self.listbox.append(row)
            self.list_rows[m.name] = row
        if self.selected and self.selected not in self.list_rows:
            self.selected = None

    # ---------- UI refresh ----------
    def refresh_ui(self):
        for name, r in self.list_rows.items():
            m = self.model.monitors.get(name)
            if not m:
                continue
            r.set_title(f"{m.name} — {m.model}".strip(" —"))
            if not m.connected:
                r.set_subtitle("offline — saved rule will be preserved")
            else:
                r.set_subtitle(f"{m.w}x{m.h}@{m.rate or round(m.rate_f, 1)}Hz · "
                               f"scale {fmt_num(m.scale)} · at {m.x}x{m.y}")
        warns = self.model.overlaps()
        status = []
        if self.model.note:
            status.append(self.model.note)
        if warns:
            status.append("⚠ overlapping layout: " +
                          ", ".join(f"{a}∩{b}" for a, b in warns))
        self.status_label.set_text("\n".join(status))
        self.build_detail()
        self.canvas.queue_draw()

    def build_detail(self):
        slot = self.detail_slot
        if (cur := slot.get_first_child()) is not None:
            slot.remove(cur)
        g = Adw.PreferencesGroup(title="Selected output")
        slot.append(g)
        m = self.model.monitors.get(self.selected)
        if not m:
            g.add(Adw.ActionRow(title="no output selected",
                                subtitle="click a rectangle on the canvas or pick one above"))
            return
        if m.w == 0 or not m.modes:
            g.add(Adw.ActionRow(title=m.name,
                                subtitle="offline and never seen this session — no modes known"))
            return

        res_list = m.resolutions()
        resrow = Adw.ComboRow(title="Resolution")
        resrow.set_model(Gtk.StringList.new([f"{w}x{h}" for w, h in res_list]))
        try:
            resrow.set_selected(res_list.index((m.w, m.h)))
        except ValueError:
            resrow.set_selected(0)

        ratrow = Adw.ComboRow(title="Refresh rate")
        self._ratrow = ratrow
        self._resrow = resrow
        self._res_list = res_list

        def fill_rates():
            w, h = res_list[resrow.get_selected()]
            rates = m.rates_for(w, h)
            names = [f"{r} Hz" for r, _ in rates] or ["(no modes)"]
            ratrow.set_model(Gtk.StringList.new(names))
            idx = 0
            for i, (_r, rf) in enumerate(rates):
                if abs(rf - m.rate_f) < 0.05:
                    idx = i
            ratrow.set_selected(idx)
        fill_rates()

        def on_res(_row, _pspec):
            w, h = res_list[resrow.get_selected()]
            m.w, m.h = w, h
            rates = m.rates_for(w, h)
            if rates:
                i = min(ratrow.get_selected(), len(rates) - 1)
                m.rate, m.rate_f = rates[i]
            self.refresh_ui()

        def on_rate(_row, _pspec):
            w, h = res_list[resrow.get_selected()]
            rates = m.rates_for(w, h)
            if rates:
                i = min(ratrow.get_selected(), len(rates) - 1)
                m.rate, m.rate_f = rates[i]
            self.update_subtitles_only()

        resrow.connect("notify::selected", on_res)
        resrow.connect("notify::selected", fill_rates)
        ratrow.connect("notify::selected", on_rate)

        scalrow = Adw.ComboRow(title="Scale")
        valid = [s for s in SCALE_CHOICES
                 if (m.w / s).is_integer() and (m.h / s).is_integer()]
        if m.scale not in valid:
            valid = sorted(set(valid + [m.scale]))
        scalrow.set_model(Gtk.StringList.new([fmt_num(s) for s in valid]))
        scalrow.set_selected(valid.index(m.scale))

        def on_scale(_row, _pspec):
            m.scale = valid[scalrow.get_selected()]
            self.refresh_ui()
        scalrow.connect("notify::selected", on_scale)

        yrow = Adw.SpinRow.new_with_range(-20000, 20000, 1)
        yrow.set_title("Vertical offset Y (logical px)")
        yrow.set_subtitle("positive Y = lower on the desk; X is automatic (row stays packed)")
        yrow.set_value(float(m.y))

        def on_y(row):
            m.y = int(row.get_value())
            self.update_subtitles_only()
        yrow.connect("changed", on_y)

        for row in (resrow, ratrow, scalrow, yrow):
            g.add(row)
        g.add(Adw.ActionRow(title="EDID",
                            subtitle=f"{len(m.modes)} mode(s) · panel {m.phys_mm[0]}x{m.phys_mm[1]} mm"))

    def update_subtitles_only(self):
        for name, r in self.list_rows.items():
            m = self.model.monitors.get(name)
            if m and m.connected:
                r.set_subtitle(
                    f"{m.w}x{m.h}@{m.rate or round(m.rate_f, 1)}Hz · "
                    f"scale {fmt_num(m.scale)} · at {m.x}x{m.y}")
        self.canvas.queue_draw()

    def on_select_row(self, _lb, row):
        self.selected = getattr(row, "mon_name", None) if row else None
        self.build_detail()
        self.canvas.queue_draw()

    # ---------- canvas ----------
    def on_draw(self, _area, cr, w, h):
        x0, y0, bw, bh = self.model.bounds()
        pad = 40
        s = min((w - 2 * pad) / bw, (h - 2 * pad) / bh)
        ox = (w - bw * s) / 2 - x0 * s
        oy = (h - bh * s) / 2 - y0 * s
        self._view = (s, ox, oy)

        def W(px, py):
            return px * s + ox, py * s + oy

        cr.set_source_rgb(0.11, 0.12, 0.14)
        cr.paint()

        for m in self.model.ordered():
            if m.w == 0:
                continue
            lw, lh = m.logical
            px, py = W(m.x, m.y)
            wpx, hpx = lw * s, lh * s
            sel = m.name == self.selected
            held = bool(self._drag) and self._drag["m"] is m
            if not m.connected:
                cr.set_source_rgba(0.30, 0.32, 0.36, 0.9)
            elif held:
                cr.set_source_rgb(0.20, 0.45, 0.70)
            elif sel:
                cr.set_source_rgb(0.16, 0.35, 0.55)
            else:
                cr.set_source_rgb(0.30, 0.33, 0.38)
            cr.rectangle(px, py, wpx, hpx)
            cr.fill_preserve()
            cr.set_source_rgb(0.9, 0.93, 0.96 if held else 0.92)
            cr.set_line_width(3 if held else (2 if sel else 1.2))
            cr.stroke()
            if not m.connected:
                cr.set_source_rgba(0.9, 0.5, 0.2, 0.9)
                cr.set_line_width(2)
                cr.set_dash([6, 4])
                cr.rectangle(px, py, wpx, hpx)
                cr.stroke()
                cr.set_dash([])
            if wpx > 90:
                layout = PangoCairo.create_layout(cr)
                desc = Pango.FontDescription("Sans Bold 12")
                if wpx < 160:
                    desc.set_size(Pango.SCALE * 8)
                layout.set_font_description(desc)
                lines = [m.name,
                         f"{m.w}x{m.h}@{m.rate or '?'}Hz · ×{fmt_num(m.scale)}",
                         f"pos {m.x}, {m.y}  ({lw}x{lh} logical)"]
                layout.set_text("\n".join(lines), -1)
                ink, logical = layout.get_pixel_extents()
                bx, by = px + 8, py + 6
                bw, bh = logical.width + 10, logical.height + 8
                cr.set_source_rgba(0, 0, 0, 0.55)
                cr.rectangle(bx, by, bw, bh)
                cr.fill()
                cr.set_source_rgb(0.95, 0.96, 0.98)
                cr.move_to(bx + 5, by + 4)
                PangoCairo.update_layout(cr, layout)
                PangoCairo.show_layout(cr, layout)

        oxp, oyp = W(0, 0)  # origin crosshair: 0,0 anchor for positions
        cr.set_source_rgba(0.9, 0.8, 0.2, 0.8)
        cr.set_line_width(1)
        cr.move_to(oxp - 8, oyp)
        cr.line_to(oxp + 8, oyp)
        cr.move_to(oxp, oyp - 8)
        cr.line_to(oxp, oyp + 8)
        cr.stroke()

    def to_world(self, sx, sy):
        if not self._view:
            return 0, 0
        s, ox, oy = self._view
        return (sx - ox) / s, (sy - oy) / s

    def hit(self, wx, wy):
        """Returns (monitor, zone) where zone is 'edge' (right border strip) or 'body'.
        Edge width is fixed in SCREEN px, so it stays grabbable at any canvas zoom."""
        s = self._view[0] if self._view else 1.0
        edge_w = self.EDGE_PX / max(s, 0.01)
        for m in reversed(self.model.ordered()):
            if m.w == 0:
                continue
            lw, lh = m.logical
            if not (m.x <= wx < m.x + lw and m.y <= wy < m.y + lh):
                continue
            if wx >= m.x + lw - edge_w:
                return m, "edge"
            return m, "body"
        return None, None

    def on_press(self, ctrl, n_press, x, y):
        wx, wy = self.to_world(x, y)
        m, zone = self.hit(wx, wy)
        if not m:
            return
        self.selected = m.name
        self.listbox.select_row(self.list_rows.get(m.name))
        self.build_detail()
        self._drag = {"m": m, "mode": zone, "dx": wx - m.x, "dy": wy - m.y,
                      "sx": wx, "moved": False}
        self.canvas.set_cursor(Gdk.Cursor.new_from_name(
            "ew-resize" if zone == "edge" else "grabbing", None))
        self.canvas.queue_draw()

    def on_motion(self, _ctrl, x, y):
        wx, wy = self.to_world(x, y)
        if not self._drag:
            m, zone = self.hit(wx, wy)
            want = {"edge": "ew-resize", "body": "grab"}.get(zone, "default")
            self.canvas.set_cursor(Gdk.Cursor.new_from_name(want, None))
            return
        d = self._drag
        m = d["m"]
        if abs(wx - d["sx"]) > 4:
            d["moved"] = True
        if d["mode"] == "body":
            # X is NEVER free: tentatively place at cursor, then the packer decides
            # the order (by centers) — neighbours slide aside live, the box you
            # hold only ever occupies a slot in the row. Drag 10000px = rightmost.
            m.x = int(round(wx - d["dx"]))
            m.y = int(round(wy - d["dy"]))
            self.model.pack_row()
        else:
            # resize: tentatively show nearest EDID size, neighbors stay put
            tgt_w = int(round(wx - m.x))
            got = m.pick_resize(tgt_w)
            if got:
                m.w, m.h, m.rate, m.rate_f = got
        self.update_subtitles_only()

    def on_release(self, ctrl, n_press, x, y):
        if not self._drag:
            return
        d = self._drag
        if d["moved"] or d["mode"] == "edge":
            self.model.pack_row()  # monitors can NEVER be pulled apart
            self.model.save_state()
        self._drag = None
        self.canvas.set_cursor(Gdk.Cursor.new_from_name("default", None))
        self.refresh_ui()

    EDGE_PX = 18  # world-px grab strip on each rectangle's right edge

    # ---------- actions ----------
    def toast(self, msg):
        self.toast_overlay.add_toast(Adw.Toast(title=msg, timeout=6))

    def on_reload(self, _btn):
        """Discard unsaved edits: re-pull live state (offline outputs keep saved)."""
        try:
            self.model.refresh_live()
        except Exception as e:  # noqa: BLE001
            self.toast(f"reload failed: {e}")
            return
        self.build_output_rows()
        self.refresh_ui()
        self.toast("reloaded live state")

    def on_write_only(self, _btn):
        backup_lua_once()
        MONITORS_LUA.write_text(self.model.gen_lua())
        self.model.save_state()
        self.toast("wrote monitors.lua (no reload)")

    def on_apply(self, _btn):
        self.model.pack_row()  # enforce the magnetic invariant before writing
        text = self.model.gen_lua()
        current = MONITORS_LUA.read_text() if MONITORS_LUA.is_file() else ""
        if text == current:
            self.toast("already in sync — nothing to apply")
            return
        backup_lua_once()
        MONITORS_LUA.write_text(text)
        self.model.save_state()
        rc, out, err = sh("hyprctl", "reload", env_extra=hypr_env())
        if rc != 0:
            self.toast(f"reload failed: {(err or out).strip()[:180]}")
            return
        GLib.timeout_add_seconds(2, self.verify_after_apply)

    def verify_after_apply(self):
        try:
            data = hyprctl_json("monitors", "all", "-j")
        except Exception as e:  # noqa: BLE001
            self.toast(f"verify failed: {e}")
            return False
        by_name = {d["name"]: d for d in data}
        problems = []
        for m in self.model.monitors.values():
            d = by_name.get(m.name)
            if not d:
                if m.connected:
                    problems.append(f"{m.name}: went missing after reload")
                continue
            got_mode = f"{int(d['width'])}x{int(d['height'])}@{round(float(d['refreshRate']), 2)}"
            want_mode = f"{m.w}x{m.h}@{round(m.rate_f, 2)}"
            if got_mode != want_mode:
                problems.append(f"{m.name}: wanted {want_mode}, actual {got_mode}")
            got_xy = (int(float(d["x"])), int(float(d["y"])))
            if got_xy != (m.x, m.y):
                problems.append(f"{m.name}: wanted ({m.x},{m.y}), actual {got_xy}")
            if abs(float(d["scale"]) - m.scale) > 0.01:
                problems.append(f"{m.name}: wanted scale {m.scale}, actual {d['scale']}")
        logerr = ""
        env = hypr_env()
        lp = Path(env.get("XDG_RUNTIME_DIR", "")) / "hypr" / \
            env.get("HYPRLAND_INSTANCE_SIGNATURE", "") / "hyprland.log"
        if lp.is_file():
            tail = lp.read_text(errors="replace")[-4000:]
            hits = [l for l in tail.splitlines() if "lua" in l.lower() and "error" in l.lower()]
            if hits:
                logerr = "\n".join(hits[-3:])
        if problems or logerr:
            body = "APPLIED WITH DRIFT:\n" + "\n".join(problems) + \
                   ("\n" + logerr if logerr else "")
            dlg = Adw.MessageDialog(transient_for=self.win, heading="Layout drift", body=body)
            dlg.add_response("ok", "OK")
            dlg.present()
        else:
            n = sum(1 for m in self.model.monitors.values() if m.connected)
            self.toast(f"applied — {n} outputs reloaded & verified ✓")
        self.refresh_ui()
        return False


def _dump_tree(w, depth=0):
    alloc = ""
    try:
        a = w.get_allocated_size() if hasattr(w, "get_allocated_size") else (w.get_width(), w.get_height())
        alloc = f"{a[0]}x{a[1]}"
    except Exception:
        pass
    print(f"{'  '*depth}{w.__class__.__name__} vis={w.get_visible()} mapped={w.get_mapped()} size={alloc}"
          f" text={getattr(w, 'get_label', lambda: '')() or getattr(w, 'get_text', lambda: '')()}"[:200])
    for c in (w.get_first_child(),):
        while c:
            _dump_tree(c, depth + 1)
            c = c.get_next_sibling()


def main():
    app = Deskman()
    if "--debug-tree" in sys.argv:
        def dump():
            _dump_tree(app.win)
            app.quit()
            return False
        GLib.timeout_add_seconds(3, dump)
        sys.argv.remove("--debug-tree")
    return app.run(None)


if __name__ == "__main__":
    sys.exit(main())
